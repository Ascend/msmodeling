"""Verify semantic candidates reach scripts generated by the unchanged plugin."""

import importlib.util
import json
import os
import shlex
import sys
import types
from pathlib import Path
from types import SimpleNamespace

import pytest

from optix.config.config import OptimizerConfigField
from optix.optimizer.multihost_adapter import run_multihost_trial

PLUGIN_DIR = Path(__file__).resolve().parents[4] / "contrib/optix/multihost_infer"
_PLUGIN_PACKAGE = "multihost_inference_optimization"


def _plugin_module_names() -> list[str]:
    return [name for name in sys.modules if name == _PLUGIN_PACKAGE or name.startswith(f"{_PLUGIN_PACKAGE}.")]


def field(name, value, position="run"):
    return OptimizerConfigField(name=name, value=value, config_position=position, dtype="str")


def simulator(others=""):
    return SimpleNamespace(
        config=SimpleNamespace(command=SimpleNamespace(others=others)),
        remote_executor=SimpleNamespace(config=SimpleNamespace(env={}, workers=[object()], chips_per_node=8)),
    )


@pytest.mark.parametrize(
    "fields,others",
    [
        ([field("api_server_count", 2)], ""),
        ([field("api_server_count", 2, "env")], ""),
        ([], "--api-server-count 2"),
        ([field("dp", 3)], ""),
        ([field("tp", 2), field("dp", 2)], ""),
        ([field("tp", 4), field("dp", 2), field("pcp", 4)], ""),
        ([], "--data-parallel-size=3"),
        ([field("dp", 4), field("tp", 4), field("pp", 2)], ""),
        ([], "--data-parallel-address other"),
        ([], "--tensor-parallel-size $UNKNOWN"),
        ([field("OPTIX_AGENT_SERVE_ARGS", "bad", "env")], ""),
    ],
)
def test_unsupported_inputs_fail_before_service_launch(fields, others):
    sim = simulator(others)
    sim.run = lambda _: pytest.fail("invalid input launched the service")
    with pytest.raises(ValueError):
        run_multihost_trial(sim, fields)
    assert sim.config.command.others == others


def test_restores_command_on_launch_failure():
    sim = simulator("--seed 42")

    def fail(_):
        assert sim.config.command.others == "$OPTIX_AGENT_SERVE_ARGS"
        raise RuntimeError("worker failed")

    sim.run = fail
    with pytest.raises(RuntimeError, match="worker failed"):
        run_multihost_trial(sim, [field("tp", 8)])
    assert sim.config.command.others == "--seed 42"


@pytest.mark.parametrize("engine", ["multihost_infer", "vllm"])
def test_scheduler_adapts_only_multihost_and_resets_previous_plan(engine, monkeypatch):
    from optix.optimizer import scheduler as module

    calls = []
    fields = (field("tp", 4),)
    scheduler = SimpleNamespace(
        engine=engine,
        benchmark=SimpleNamespace(),
        simulate_run_info=fields,
        simulator=SimpleNamespace(run=lambda params: calls.append(("direct", params))),
        simulate_launch_plan={"old": "stale"},
        wait_simulate=lambda: None,
    )
    plan = {"start_node.sh": "measured"}
    monkeypatch.setattr(module, "run_multihost_trial", lambda sim, params: calls.append(("adapted", params)) or plan)
    module.Scheduler.run_simulate(scheduler, None, fields)
    assert calls == [("adapted" if engine == "multihost_infer" else "direct", fields)]
    assert scheduler.simulate_launch_plan == (plan if engine == "multihost_infer" else {})


def _load_plugin(monkeypatch, filename):
    monkeypatch.syspath_prepend(str(PLUGIN_DIR))
    fabric = types.ModuleType("fabric")
    fabric.Connection = object
    fabric.Config = object
    monkeypatch.setitem(sys.modules, "fabric", fabric)
    # simulator.py imports vllm_worker_manager → ssh_remote_tools, which binds
    # FabricConfig at import time. Drop those package entries after loading so
    # later tests do not reuse Config=object from this stub.
    snapshot = {name: sys.modules[name] for name in _plugin_module_names()}
    spec = importlib.util.spec_from_file_location(
        "adapter_" + filename[:-3], PLUGIN_DIR / "multihost_inference_optimization" / filename
    )
    module = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(module)
    finally:
        for name in _plugin_module_names():
            sys.modules.pop(name, None)
        sys.modules.update(snapshot)
    return module


def test_load_plugin_does_not_cache_stub_ssh_tools(monkeypatch):
    before = {name: sys.modules[name] for name in _plugin_module_names()}
    _load_plugin(monkeypatch, "simulator.py")
    assert {name: sys.modules.get(name) for name in before} == before
    assert [name for name in _plugin_module_names() if name not in before] == []


def test_candidates_reach_original_plugin_node_scripts(tmp_path, monkeypatch):
    plugin = _load_plugin(monkeypatch, "simulator.py")
    builder = _load_plugin(monkeypatch, "build_shell_scripts.py")
    cluster = tmp_path / "cluster.toml"
    cluster.write_text(
        '''[vllm_mix]
chips_per_node=8
data_parallel_rpc_port=20000
[[vllm_mix.node]]
host="node0"
nic_name="eth0"
[[vllm_mix.workers]]
host="node1"
nic_name="eth0"
''',
        encoding="utf-8",
    )
    monkeypatch.setenv("CLUSTER_CONFIG_PATH", str(cluster))
    sim = plugin.MultiHostSimulator.__new__(plugin.MultiHostSimulator)
    sim.config = SimpleNamespace(
        command=SimpleNamespace(
            model="/weights/model",
            served_model_name="model",
            port="8000",
            others='--tensor-parallel-size=4 --enforce-eager --max-num-seqs 128 --speculative-config \'{"method":"mtp"}\'',
        )
    )
    scripts = tmp_path / "scripts"
    sim.remote_executor = SimpleNamespace(
        config=SimpleNamespace(env={}, workers=[object()], chips_per_node=8),
        set_build_scripts_dir=lambda _: None,
        get_build_scripts_dir=lambda: scripts,
        upload_all_scripts=lambda: None,
        cleanup_all_workers=lambda: None,
        start_workers=lambda _: None,
    )
    sim.process_name = ""
    sim._get_output_dir = lambda: scripts
    sim._resolve_nic_names = lambda: {"node0": "eth0", "node1": "eth0"}
    sim._launch_node_local = lambda: None

    def build(cmd, **_):
        monkeypatch.setattr(sys, "argv", cmd[1:])
        builder.main()
        return SimpleNamespace(returncode=0, stdout="", stderr="")

    monkeypatch.setattr(plugin.subprocess, "run", build)
    original = sim.config.command.others
    try:
        for tp, dp, pcp, position in ((8, 2, 1, "run"), (4, 4, 1, "env"), (2, 2, 4, "run")):
            command = original if position == "run" else original.replace("--tensor-parallel-size=4 ", "")
            sim.config.command.others = command
            fields = [
                field("tp", tp, position),
                field("dp", dp, position),
                field("pcp", pcp, position),
                field("enforce_eager", tp == 8),
                field("MAX_NUM_SEQS", 64),
                field("MAX_NUM_SEQS", 32, "env"),
                field("CONCURRENCY", 16, "env"),
                field("num_speculative_tokens", 3),
                field("additional_config", '{"literal":"$KEEP_ME"}'),
                field("api_server_count", 1),
            ]
            plan = run_multihost_trial(sim, fields)
            assert sim.config.command.others == command
            assert set(plan) == {"start_node.sh", "start_work_0.sh"}
            for name, script in plan.items():
                argv = shlex.split(script.split("vllm serve", 1)[1].replace("\\\n", " "))
                assert json.loads(argv[argv.index("--additional-config") + 1]) == {"literal": "$KEEP_ME"}
                assert "$OPTIX_AGENT_SERVE_ARGS" not in script
                assert argv[argv.index("--tensor-parallel-size") + 1] == str(tp)
                assert argv[argv.index("--data-parallel-size") + 1] == str(dp)
                if pcp != 1:
                    assert argv[argv.index("--prefill-context-parallel-size") + 1] == str(pcp)
                assert argv[argv.index("--data-parallel-size-local") + 1] == str(dp // 2)
                assert ("--enforce-eager" in argv) == (tp == 8)
                assert argv.count("--max-num-seqs") == 1
                assert argv[argv.index("--max-num-seqs") + 1] == "64"
                assert "--concurrency" not in argv
                assert json.loads(argv[argv.index("--speculative-config") + 1]) == {
                    "method": "mtp",
                    "num_speculative_tokens": 3,
                }
                assert ("--headless" in argv) == (name != "start_node.sh")
                assert (
                    "--api-server-count" not in argv
                    if name != "start_node.sh"
                    else argv[argv.index("--api-server-count") + 1] == "1"
                )
            os.close(sim.run_log_fp)
            sim.run_log_fp = None
    finally:
        if sim.run_log_fp is not None:
            os.close(sim.run_log_fp)
