import torch
from tensor_cast.utils import register_tensor_cast_op
from tensor_cast.performance_model.op_invoke_info import OpInvokeInfo
from tensor_cast.compilation.patterns import register_pattern

# ========== 0. Plugin namespace ==========
__plugin_namespace__ = "user_fusion"


# ========== 1. Virtual op declaration ==========
@register_tensor_cast_op("user_fusion_mm_relu")
def _meta_impl(x: torch.Tensor, w: torch.Tensor) -> torch.Tensor:
    """Meta impl: output is the mm result shape (m, n), relu is elementwise."""
    return torch.empty(x.size(0), w.size(1), dtype=x.dtype, device="meta")


# ========== 2. FX Pattern + Replacement ==========
def _pattern(x, w):
    """relu(mm(x, w)) — the low-level chain to match."""
    return torch.ops.aten.relu(torch.ops.aten.mm(x, w))


def _replacement(x, w):
    return torch.ops.tensor_cast.user_fusion_mm_relu(x, w)


# ========== 3. Performance properties ==========
@OpInvokeInfo.register_op_properties(torch.ops.tensor_cast.user_fusion_mm_relu.default)
def _performance_props(info: OpInvokeInfo) -> OpInvokeInfo.PerformanceProperties:
    x, w = info.args
    m, k, n = x.size(0), x.size(1), w.size(1)

    props = info.get_memory_access_properties()
    props.compute_ops[x.dtype] = OpInvokeInfo.ComputeOps(
        mma_ops=m * n * k * 2,  # mm FMA ops
        gp_ops=m * n,  # relu elementwise compare-and-select
    )
    return props


# ========== 4. Plugin entry ==========
def register_all_patterns():
    # Each example input is its own torch.empty(...) — NOT [torch.empty(...)] * 2.
    # Sharing one object across params makes inductor's tracer dedup them by
    # identity, collapsing the pattern (e.g. into mm(x, x)) so it never matches.
    example_inputs = [
        torch.empty(1, 1, dtype=torch.float16, device="meta"),  # x
        torch.empty(1, 1, dtype=torch.float16, device="meta"),  # w
    ]
    register_pattern(
        name=f"{__plugin_namespace__}_mm_relu",
        pattern=_pattern,
        replacement=_replacement,
        example_inputs=example_inputs,
    )


# ========== 5. Metadata ==========
